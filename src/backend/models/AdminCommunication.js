import mongoose from 'mongoose';

const adminCommunicationSchema = new mongoose.Schema({
  messageId: {
    type: String,
    required: true,
    unique: true,
    trim: true,
  },
  senderId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: [true, 'Message must have a sender'],
  },
  receiverId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: [true, 'Message must have a receiver'],
  },
  senderRole: {
    type: String,
    enum: ['admin', 'vendor', 'rider', 'user'],
    required: true,
  },
  receiverRole: {
    type: String,
    enum: ['admin', 'vendor', 'rider', 'user'],
    required: true,
  },
  subject: {
    type: String,
    required: [true, 'Message must have a subject'],
    trim: true,
    maxlength: [200, 'Subject cannot exceed 200 characters'],
  },
  message: {
    type: String,
    required: [true, 'Message content is required'],
    trim: true,
    maxlength: [2000, 'Message cannot exceed 2000 characters'],
  },
  messageType: {
    type: String,
    enum: [
      'general',
      'order_related',
      'payment_issue',
      'account_issue',
      'support_request',
      'feedback_request',
      'promotion',
      'warning',
      'suspension_notice',
      'verification_request',
      'policy_update',
      'system_notification'
    ],
    default: 'general',
  },
  priority: {
    type: String,
    enum: ['low', 'medium', 'high', 'urgent'],
    default: 'medium',
  },
  status: {
    type: String,
    enum: ['sent', 'delivered', 'read', 'replied', 'archived'],
    default: 'sent',
  },
  readStatus: {
    isRead: {
      type: Boolean,
      default: false,
    },
    readAt: {
      type: Date,
    },
  },
  replyDetails: {
    hasReplied: {
      type: Boolean,
      default: false,
    },
    replyCount: {
      type: Number,
      default: 0,
    },
    lastReplyAt: {
      type: Date,
    },
    lastReplyBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
    },
  },
  attachments: [{
    type: {
      type: String,
      enum: ['image', 'document', 'pdf', 'video', 'audio'],
      required: true,
    },
    url: {
      type: String,
      required: true,
    },
    filename: {
      type: String,
      required: true,
    },
    size: {
      type: Number,
      required: true,
    },
    uploadedAt: {
      type: Date,
      default: Date.now,
    },
  }],
  metadata: {
    orderId: mongoose.Schema.Types.ObjectId,
    refundId: mongoose.Schema.Types.ObjectId,
    supportTicketId: String,
    campaignId: mongoose.Schema.Types.ObjectId,
    originalMessageId: mongoose.Schema.Types.ObjectId, // For threaded conversations
    tags: [String],
    category: String,
    escalationLevel: {
      type: Number,
      default: 0,
      min: 0,
      max: 3,
    },
    autoGenerated: {
      type: Boolean,
      default: false,
    },
    scheduledSendTime: Date,
  },
  deliveryDetails: {
    sentAt: {
      type: Date,
      default: Date.now,
    },
    deliveredAt: Date,
    deliveryMethod: {
      type: String,
      enum: ['in_app', 'email', 'sms', 'push', 'all'],
      default: 'in_app',
    },
    deliveryAttempts: {
      type: Number,
      default: 0,
    },
    lastDeliveryAttempt: Date,
    deliveryErrors: [{
      error: String,
      timestamp: Date,
      method: String,
    }],
  },
  responseTracking: {
    expectedResponseTime: Date,
    actualResponseTime: Date,
    responseQuality: {
      type: String,
      enum: ['excellent', 'good', 'average', 'poor'],
    },
    satisfactionRating: {
      type: Number,
      min: 1,
      max: 5,
    },
  },
  organizationId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Organization',
    default: null,
  },
}, {
  timestamps: true,
});

// Indexes for efficient queries
adminCommunicationSchema.index({ senderId: 1, createdAt: -1 });
adminCommunicationSchema.index({ receiverId: 1, createdAt: -1 });
adminCommunicationSchema.index({ senderRole: 1, receiverRole: 1 });
adminCommunicationSchema.index({ status: 1, createdAt: -1 });
adminCommunicationSchema.index({ 'readStatus.isRead': 1, createdAt: -1 });
adminCommunicationSchema.index({ messageType: 1, createdAt: -1 });
adminCommunicationSchema.index({ priority: 1, createdAt: -1 });

// Compound indexes for admin dashboard queries
adminCommunicationSchema.index({ 
  senderRole: 'admin', 
  receiverRole: 1, 
  createdAt: -1 
});

adminCommunicationSchema.index({ 
  receiverRole: 'admin', 
  senderRole: 1, 
  createdAt: -1 
});

adminCommunicationSchema.index({ 
  status: 1, 
  priority: 1, 
  createdAt: -1 
});

// Auto-generate messageId before saving
adminCommunicationSchema.pre('save', async function(next) {
  if (this.isNew && !this.messageId) {
    const count = await this.constructor.countDocuments();
    this.messageId = `MSG${String(count + 1).padStart(8, '0')}`;
  }
  next();
});

// Update reply details when reply is created
adminCommunicationSchema.methods.addReply = function(replyBy, replyContent) {
  this.replyDetails.hasReplied = true;
  this.replyDetails.replyCount += 1;
  this.replyDetails.lastReplyAt = new Date();
  this.replyDetails.lastReplyBy = replyBy;
  return this.save();
};

// Mark message as read
adminCommunicationSchema.methods.markAsRead = function() {
  this.readStatus.isRead = true;
  this.readStatus.readAt = new Date();
  this.status = 'read';
  return this.save();
};

const AdminCommunication = mongoose.model('AdminCommunication', adminCommunicationSchema);

export default AdminCommunication;
