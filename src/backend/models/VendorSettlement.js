/**
 * Vendor Settlement model for managing vendor payouts and settlements
 */
import mongoose from 'mongoose';

const settlementItemSchema = new mongoose.Schema({
  orderId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Order',
    required: true,
  },
  orderNumber: {
    type: String,
    required: true,
  },
  orderDate: {
    type: Date,
    required: true,
  },
  grossAmount: {
    type: Number,
    required: true,
    min: 0,
  },
  commissionAmount: {
    type: Number,
    required: true,
    min: 0,
  },
  gstAmount: {
    type: Number,
    required: true,
    min: 0,
  },
  /**
   * Packing the customer paid on this order, which the vendor keeps, and the
   * GST charged on it, which they do not. Held per item rather than only in
   * the summary so a vendor querying one order can be shown that order.
   */
  packagingAmount: {
    type: Number,
    default: 0,
    min: 0,
  },
  packagingGstAmount: {
    type: Number,
    default: 0,
    min: 0,
  },
  /** The part of the discount this vendor agreed to fund. */
  vendorFundedDiscount: {
    type: Number,
    default: 0,
    min: 0,
  },
  /** The statement lines, in the order the vendor reads them. */
  breakdown: [
    {
      _id: false,
      label: { type: String },
      value: { type: Number },
    },
  ],
  platformFee: {
    type: Number,
    required: true,
    min: 0,
  },
  netAmount: {
    type: Number,
    required: true,
    min: 0,
  },
  cancellationPenalty: {
    type: Number,
    default: 0,
    min: 0,
  },
  adjustmentAmount: {
    type: Number,
    default: 0,
  },
  adjustmentReason: {
    type: String,
  },
}, {
  _id: true,
});

const vendorSettlementSchema = new mongoose.Schema({
  settlementNumber: {
    type: String,
    required: true,
    unique: true,
  },
  vendorId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: [true, 'Vendor ID is required'],
  },
  restaurantId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Restaurant',
    required: [true, 'Restaurant ID is required'],
  },
  settlementPeriod: {
    startDate: {
      type: Date,
      required: true,
    },
    endDate: {
      type: Date,
      required: true,
    },
  },
  status: {
    type: String,
    enum: ['pending', 'processing', 'approved', 'paid', 'failed', 'cancelled'],
    default: 'pending',
  },
  items: [settlementItemSchema],
  summary: {
    totalOrders: {
      type: Number,
      required: true,
      min: 0,
    },
    grossRevenue: {
      type: Number,
      required: true,
      min: 0,
    },
    totalCommission: {
      type: Number,
      required: true,
      min: 0,
    },
    totalGST: {
      type: Number,
      required: true,
      min: 0,
    },
    totalPlatformFee: {
      type: Number,
      required: true,
      min: 0,
    },
    totalPackaging: {
      type: Number,
      default: 0,
      min: 0,
    },
    totalVendorFundedDiscount: {
      type: Number,
      default: 0,
      min: 0,
    },
    totalPenalties: {
      type: Number,
      default: 0,
      min: 0,
    },
    totalAdjustments: {
      type: Number,
      default: 0,
    },
    netPayable: {
      type: Number,
      required: true,
      min: 0,
    },
    tdsDeducted: {
      type: Number,
      default: 0,
      min: 0,
    },
    finalAmount: {
      type: Number,
      required: true,
      min: 0,
    },
  },
  bankDetails: {
    accountHolderName: {
      type: String,
      required: true,
    },
    accountNumber: {
      type: String,
      required: true,
    },
    bankName: {
      type: String,
      required: true,
    },
    ifsc: {
      type: String,
      required: true,
    },
    branchName: String,
  },
  paymentInfo: {
    transactionId: String,
    paymentDate: Date,
    paymentMethod: {
      type: String,
      enum: ['bank_transfer', 'upi', 'cheque', 'cash'],
      default: 'bank_transfer',
    },
    utrNumber: String,
    referenceNumber: String,
  },
  approvalInfo: {
    approvedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
    },
    approvedAt: Date,
    approvalNotes: String,
  },
  processingInfo: {
    processedBy: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
    },
    processedAt: Date,
    processingNotes: String,
  },
  failureReason: {
    type: String,
  },
  retryCount: {
    type: Number,
    default: 0,
    min: 0,
  },
  nextRetryAt: {
    type: Date,
  },
  documents: [{
    type: {
      type: String,
      enum: ['invoice', 'receipt', 'statement', 'other'],
    },
    filename: String,
    url: String,
    uploadedAt: {
      type: Date,
      default: Date.now,
    },
  }],
  notes: {
    type: String,
  },
  autoGenerated: {
    type: Boolean,
    default: false,
  },
  dueDate: {
    type: Date,
  },
}, {
  timestamps: true,
});

// Generate settlement number before saving
vendorSettlementSchema.pre('save', async function(next) {
  if (this.isNew && !this.settlementNumber) {
    const year = new Date().getFullYear();
    const month = String(new Date().getMonth() + 1).padStart(2, '0');
    const count = await this.constructor.countDocuments({
      createdAt: {
        $gte: new Date(new Date().getFullYear(), new Date().getMonth(), 1),
        $lt: new Date(new Date().getFullYear(), new Date().getMonth() + 1, 1),
      }
    });
    this.settlementNumber = `VST-${year}${month}-${String(count + 1).padStart(4, '0')}`;
  }
  next();
});

// Calculate summary from items
vendorSettlementSchema.methods.calculateSummary = function() {
  const summary = {
    totalOrders: this.items.length,
    grossRevenue: 0,
    totalCommission: 0,
    totalGST: 0,
    totalPlatformFee: 0,
    totalPackaging: 0,
    totalVendorFundedDiscount: 0,
    totalPenalties: 0,
    totalAdjustments: 0,
    netPayable: 0,
    tdsDeducted: 0,
    finalAmount: 0,
  };

  this.items.forEach(item => {
    summary.grossRevenue += item.grossAmount;
    summary.totalCommission += item.commissionAmount;
    // Packing GST is GST: the vendor passes it on either way.
    summary.totalGST += item.gstAmount + (item.packagingGstAmount || 0);
    summary.totalPlatformFee += item.platformFee;
    summary.totalPackaging += item.packagingAmount || 0;
    summary.totalVendorFundedDiscount += item.vendorFundedDiscount || 0;
    summary.totalPenalties += item.cancellationPenalty;
    summary.totalAdjustments += item.adjustmentAmount;
    // Each item's netAmount already has that order's deductions taken out.
    summary.netPayable += item.netAmount;
  });

  // Calculate TDS (2% on commission + platform fee)
  summary.tdsDeducted = Math.round((summary.totalCommission + summary.totalPlatformFee) * 0.02);
  summary.finalAmount = Math.max(0, summary.netPayable - summary.tdsDeducted);

  this.summary = summary;
  return this.save();
};

// Approve settlement
vendorSettlementSchema.methods.approve = function(approvedBy, notes) {
  this.status = 'approved';
  this.approvalInfo = {
    approvedBy,
    approvedAt: new Date(),
    approvalNotes: notes,
  };
  return this.save();
};

// Process settlement
vendorSettlementSchema.methods.process = function(processedBy, paymentInfo, notes) {
  this.status = 'paid';
  this.processingInfo = {
    processedBy,
    processedAt: new Date(),
    processingNotes: notes,
  };
  this.paymentInfo = { ...this.paymentInfo, ...paymentInfo, paymentDate: new Date() };
  return this.save();
};

const VendorSettlement = mongoose.model('VendorSettlement', vendorSettlementSchema);

export default VendorSettlement;
